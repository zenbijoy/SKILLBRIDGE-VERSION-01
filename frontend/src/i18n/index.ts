const dictionaries: Record<AppLanguage, Dictionary> = { en, bn };

function deviceLanguage(): AppLanguage {
  const locale = Intl.DateTimeFormat().resolvedOptions().locale?.toLowerCase() ?? "en";
  return locale.startsWith("bn") ? "bn" : "en";
}

export function useI18n() {
  const language = usePreferencesStore((state) => state.language);
  const useDeviceLanguage = usePreferencesStore((state) => state.useDeviceLanguage);
  const activeLanguage = useDeviceLanguage ? deviceLanguage() : language;
  return useMemo(
    () => ({
      language: activeLanguage,
      t: (key: string, fallback?: string) =>
        dictionaries[activeLanguage][key] ?? dictionaries.en[key] ?? fallback ?? key,
    }),
    [activeLanguage],
  );
}
